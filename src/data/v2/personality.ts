export function personalityFactors(
  p: Person,
  action: Action,
): Record<string, number> {
  const factors: Record<string, number> = {};
  for (const key of Object.keys(traits) as (keyof typeof traits)[])
    if (traitActions[key].includes(action))
      factors[`traço:${key}`] = ((p.traits[key] ?? 50) - 50) * 2;
  for (const key of Object.keys(values) as (keyof typeof values)[])
    if (valueActions[key].includes(action))
      factors[`valor:${key}`] = p.values[key] || 0;
  return factors;
}
